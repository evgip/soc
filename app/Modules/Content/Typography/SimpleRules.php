<?php

declare(strict_types=1);

namespace App\Modules\Content\Typography;

/**
 * Простые типографские правила (не требуют FSM).
 * 
 * Здесь собраны правила, которые можно безопасно применить регулярками,
 * так как они не зависят от сложного контекста:
 * 
 * 1. Многоточие: "..." → "…"
 * 2. Специальные символы: (c) → ©, (r) → ®, (tm) → ™, (p) → §
 * 3. Неразрывные пробелы после коротких предлогов и союзов
 *    ("в", "на", "с", "и" и т.д.) — чтобы они не отрывались от слова
 *    при переносе строки
 * 
 * Почему эти правила безопасны для регулярок:
 * - Многоточие не зависит от контекста
 * - Спецсимволы (c), (r), (tm) — фиксированные паттерны
 * - Предлоги + пробел — простой паттерн "слово + пробел"
 * 
 * Использование:
 *   $rules = new SimpleRules();
 *   $rules->apply('Привет... (c) 2026');  // → 'Привет… © 2026'
 *   $rules->apply('в лесу');               // → 'в\u{00A0}лесу' (неразрывный пробел)
 */
class SimpleRules
{
    /**
     * Короткие предлоги, союзы и частицы русского языка.
     * 
     * После них ставится неразрывный пробел (U+00A0),
     * чтобы при переносе строки они не отрывались от следующего слова.
     * 
     * Список основан на рекомендациях типографики Лебедева и Мильчина.
     */
    private const PREPOSITIONS = [
        // Предлоги
        'в', 'во', 'на', 'с', 'со', 'к', 'ко', 'о', 'об', 'обо',
        'у', 'из', 'по', 'за', 'до', 'от', 'ото', 'перед', 'над',
        'под', 'при', 'про', 'для', 'без', 'через',
        // Союзы
        'и', 'а', 'но', 'да', 'или',
        // Частицы
        'не', 'ни', 'же', 'бы', 'ли', 'ведь', 'вот',
    ];

    /**
     * Неразрывный пробел (U+00A0) в кодировке UTF-8.
     * 
     * В отличие от обычного пробела (U+0020), неразрывный пробел
     * не позволяет браузеру перенести строку в этом месте.
     */
    private const NBSP = "\xC2\xA0";

    /**
     * Применить все простые правила к тексту.
     * 
     * Порядок применения:
     * 1. Многоточие (до спецсимволов, чтобы не конфликтовать)
     * 2. Спецсимволы (c), (r), (tm), (p)
     * 3. Неразрывные пробелы после предлогов
     * 4. Чистка множественных пробелов (в конце, чтобы не ломать NBSP)
     * 
     * @param string $text Текст для обработки
     * @return string Обработанный текст
     */
    public function apply(string $text): string
    {
        // Пустой текст не обрабатываем
        if (trim($text) === '') {
            return $text;
        }

        // Правило 1: многоточие (3 и более точки → …)
        $text = preg_replace('/\.{3,}/u', '…', $text);

        // Правило 2: специальные символы (регистронезависимо)
        $text = preg_replace('/\(c\)/iu', '©', $text);
		// русское "с"
		$text = preg_replace('/\(с\)/iu', '©', $text);
		
        $text = preg_replace('/\(r\)/iu', '®', $text);
        $text = preg_replace('/\(tm\)/iu', '™', $text);
        $text = preg_replace('/\(p\)/iu', '§', $text);

        // Правило 3: неразрывный пробел после коротких предлогов
        // Паттерн: граница слова + предлог + один или более пробелов
        $pattern = '/\b(' . implode('|', self::PREPOSITIONS) . ')\s+/ui';
        
        // Применяем 3 раза, т.к. preg_replace не обрабатывает
        // перекрывающиеся совпадения за один проход
        // Пример: "в лесу и в поле" — нужно 2 итерации
        for ($i = 0; $i < 3; $i++) {
            $text = preg_replace($pattern, '$1' . self::NBSP, $text);
        }

        // Правило 4: чистка множественных обычных пробелов
        // NBSP не трогаем (они намеренно поставлены)
        $text = preg_replace('/[ \t]{2,}/', ' ', $text);

        return $text;
    }
}